// Bakes sampled ItsHover motion into Dart: per part, up to 9 channels per 30 fps frame (the painter interpolates)
// (affine a b c d e f, opacity, dash start, dash end). Only channels that move store frames.
import fs from 'fs';
import { fileURLToPath } from 'url';
import { svgPathBbox } from 'svg-path-bbox';
const app = fileURLToPath(new URL('../../app', import.meta.url));
const baked = JSON.parse(fs.readFileSync('baked.json'));
const loops = { 'cloud-1-icon': 2, 'list-globe': 2, 'list-game': 1.2, 'alarm-clock-plus-icon': .3 };
const fps = 30, r = v => +v.toFixed(3);
const chan = s => {
  let a = 0, b = 1;
  if (s.pl != null && s.da !== 'none') { const len = parseFloat(s.da); const off = -parseFloat(s.dof || 0); a = off; b = off + len; }
  return [...s.m, s.o, Math.max(0, Math.min(1, a)), Math.max(0, Math.min(1, b))].map(r);
};
const resample = (seq, dur) => {
  if (!seq.length) return [];
  const out = [];
  for (let i = 0; i <= Math.round(dur * fps); i++) {
    const t = i / fps; let j = seq.findIndex(x => x.t >= t); if (j < 0) j = seq.length - 1;
    out.push(seq[j].f);
  }
  return out;
};
let dart = `// GENERATED by tools/bake-icons/gen.mjs (ItsHover motion, Apache-2.0). Do not edit.\n// ignore_for_file: lines_longer_than_80_chars\npart of 'day_icon.dart';\n\nconst _motion = <String, _IconMotion>{\n`;
for (const [key, v] of Object.entries(baked)) {
  const keep = v.rest.map((s, i) => !(s.fill === 'none' && s.stroke === 'none') && s.disp !== 'none' ? i : -1).filter(i => i >= 0);
  // List icons sit in a grid, so each gets the same optical box: centred,
  // the longer side at 84 % of the cell, strokes kept visually equal.
  let vb = v.vb, k = 1;
  if (key.startsWith('list-')) {
    let b = [Infinity, Infinity, -Infinity, -Infinity];
    for (const i of keep) {
      const s = v.rest[i]; if (s.o < .01) continue;
      const [x0, y0, x1, y1] = svgPathBbox(s.d), [e, f] = s.m.slice(4);
      b = [Math.min(b[0], x0 + e), Math.min(b[1], y0 + f), Math.max(b[2], x1 + e), Math.max(b[3], y1 + f)];
    }
    const size = v.vb[2], sw = v.rest[keep[0]].sw;
    const side = Math.max(b[2] - b[0], b[3] - b[1]) / (.84 - sw / size);
    vb = [(b[0] + b[2] - side) / 2, (b[1] + b[3] - side) / 2, side, side];
    k = side / size;
  }
  const loop = loops[key];
  const startDur = loop ? 4 : (v.start.at(-1)?.t ?? 0), stopDur = v.stop.at(-1)?.t ?? 0;
  const start = resample(v.start, startDur), stop = resample(v.stop, stopDur);
  const parts = keep.map(i => {
    const s = v.rest[i], rest = chan(s);
    const seq = [...start, ...stop].map(f => chan(f[i]));
    const mask = rest.map((_, j) => j).filter(j => seq.some(c => Math.abs(c[j] - rest[j]) > .002));
    const fill = s.fill !== 'none', stroke = s.stroke !== 'none';
    return `    _Part(${JSON.stringify(s.d)}, fill: ${fill}, stroke: ${stroke}, width: ${r(s.sw * .875 * k)}, rest: [${rest}]${mask.length ? `, channels: [${mask}], frames: [${seq.flatMap(c => mask.map(j => c[j]))}]` : ''})`;
  });
  dart += `  '${key}': _IconMotion(\n    box: [${vb.map(r)}],\n    start: ${start.length},\n    stop: ${stop.length},\n    loop: ${loop ? Math.round(loop * fps) : 0},\n    parts: [\n${parts.join(',\n')},\n    ],\n  ),\n`;
}
// Quiet volume: ItsHover has only the loud speaker, so this one keeps its
// speaker with a single wave and stays still.
dart += `  'volume-low': _IconMotion(\n    box: [0,0,24,24],\n    start: 0,\n    stop: 0,\n    loop: 0,\n    parts: [\n${['M11 4.702a.705.705 0 0 0-1.203-.498L6.413 7.587A1.4 1.4 0 0 1 5.416 8H3a1 1 0 0 0-1 1v6a1 1 0 0 0 1 1h2.416a1.4 1.4 0 0 1 .997.413l3.383 3.384A.705.705 0 0 0 11 19.298z', 'M16 9a5 5 0 0 1 0 6'].map(d => `    _Part("${d}", fill: false, stroke: true, width: 1.75, rest: [1,0,0,1,0,0,1,0,1])`).join(',\n')},\n    ],\n  ),\n`;
// The hamburger has no ItsHover component; it stays still.
dart += `  'menu-icon': _IconMotion(\n    box: [0,0,24,24],\n    start: 0,\n    stop: 0,\n    loop: 0,\n    parts: [\n${['M4 6h16', 'M4 12h16', 'M4 18h16'].map(d => `    _Part("${d}", fill: false, stroke: true, width: 1.75, rest: [1,0,0,1,0,0,1,0,1])`).join(',\n')},\n    ],\n  ),\n};\n`;
fs.writeFileSync(`${app}/lib/theme/icon_motion.g.dart`, dart);
console.log((dart.length / 1024).toFixed(0) + ' KB');
